import { readFileSync, writeFileSync } from "node:fs";

/**
 * `packages/core/src/magazine.css` is the one stylesheet for the template.
 * `magazine-css.ts` is the same text as a string so renderPreviewPage can inline it
 * in a browser and in Node without a bundler. A test fails if they drift.
 */
const css = readFileSync("packages/core/src/magazine.css", "utf8");
const out = `// Generated by scripts/sync-magazine-css.mjs from magazine.css. Do not edit.\nexport const MAGAZINE_CSS = ${JSON.stringify(css)};\n`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync("packages/core/src/magazine-css.ts", "utf8");
  } catch {
    /* missing counts as drift */
  }
  if (current !== out) {
    console.error("packages/core/src/magazine-css.ts is out of date. Run npm run sync:css.");
    process.exit(1);
  }
} else {
  writeFileSync("packages/core/src/magazine-css.ts", out);
}
